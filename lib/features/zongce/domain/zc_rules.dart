/// 五育等次。
enum ZcGrade {
  ok('优秀'),
  good('良好'),
  pass('合格'),
  fail('不合格');

  const ZcGrade(this.label);
  final String label;
}

/// 班级排名档位（每育独立选择，unknown=不确定→按分数判断，结果偏乐观）。
enum ZcRank {
  top30('前 30%'),
  top60('前 30%~60%'),
  below('60% 以后'),
  unknown('不确定');

  const ZcRank(this.label);
  final String label;

  bool get isBelow => this == below;
}

/// 单项等次（第十条）：HTML gradeOf(score, rank)。
ZcGrade zcGradeOf(double score, ZcRank rank) {
  if (score < 60) return ZcGrade.fail;
  if (score >= 75 && !rank.isBelow) return ZcGrade.ok;
  if (score >= 65 && !rank.isBelow) return ZcGrade.good;
  return ZcGrade.pass;
}
